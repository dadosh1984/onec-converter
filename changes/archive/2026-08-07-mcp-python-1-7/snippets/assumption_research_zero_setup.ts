// GREEN: research «zero-setup» — прямая запись в 1Cv8.1CD и/или автоустановка расширения
import * as fs from 'node:fs';
import * as path from 'node:path';

export function assumption_research_zero_setup() {
  const files: Record<string, string> = {
    'docs/zero-setup.md': `# Zero-setup на приёмнике — исследование (Фаза 4)

Цель: минимальное вмешательство пользователя при переносе. Пользователь, который
не знает 1С, не должен собирать/устанавливать расширение.

## Вариант A. Прямая запись в 1Cv8.1CD приёмника (собственный writer)
- Формат 1CD разобран нашим парсером (чтение). Запись требует:
  1. запись строк в таблицы (фиксированные/переменные поля, BLOB-цепочки 256-байт чанков);
  2. обновление каталога таблиц/страниц, индексов;
  3. согласованность системных таблиц (IBVERSION, журнал, счётчики);
  4. блокировку при открытой базе (файл 1Cv8.1CL) — запись только при закрытой ИБ.
- Риск: повреждение базы -> обязательная резервная копия и верификация (verify).
- tool1cd (GPL) доказывает принципиальную возможность записи; мы пишем свою
  реализацию (логика формата — из собственного парсера, без чужого кода).
- Приоритет: после стабилизации чтения (Фаза 5) и контракта load (Фаза 4 MVP).

## Вариант B. Автоустановка расширения через 1cv8.exe DESIGNER
- Требует платформы 1С на машине пользователя (нарушает «сервер без платформы»
  только для этапа подготовки приёмника; сам MCP-сервер остаётся без платформы).
- Команда: 1cv8.exe DESIGNER /F <база> /LoadExtensionCfg <файл.cfe>
  — расширение собирается один раз из исходников, далее авто-подключение.
- Подходит пользователям с установленной платформой; для остальных — вариант A.

## Вывод
- MVP (текущая фаза): расширение, собранное в Конфигураторе (fallback).
- Целевая фича: вариант A (прямой writer) как основной, B — дополнительный.
- Следующий шаг: прототип writer'а на копии 1C_8.3 (пустая база — безопасно).
`,
  };
  const written: string[] = [];
  for (const [rel, content] of Object.entries(files)) {
    const p = path.resolve(process.cwd(), rel);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, content);
    written.push(rel);
  }
  return written.join(', ');
}
